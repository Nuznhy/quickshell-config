def hyprland(p, lua=False, appearance=None):
    """Appearance only: leave input, monitors, workspaces and bindings alone."""
    defaults = dict(radius=0, opacity=1, verticalGap=0, horizontalGap=0, innerGap=8, borderWidth=1)
    if appearance is None:
        appearance = defaults
    if not isinstance(appearance, dict):
        raise ValueError('Invalid Hyprland appearance settings.')
    values = dict(defaults, **appearance)
    for key, maximum in [('radius', 100), ('verticalGap', 40), ('horizontalGap', 40), ('innerGap', 100), ('borderWidth', 10)]:
        if type(values[key]) is not int or not 0 <= values[key] <= maximum:
            raise ValueError('Invalid Hyprland appearance: ' + key)
    if type(values['opacity']) not in (int, float) or not 0.2 <= values['opacity'] <= 1:
        raise ValueError('Invalid Hyprland appearance: opacity')
    radius, opacity = values['radius'], values['opacity']
    vertical, horizontal = values['verticalGap'], values['horizontalGap']
    gap, border = values['innerGap'], values['borderWidth']
    if lua:
        return f'''-- Generated by Quickshell; disable Hyprland appearance to restore your styling.
hl.config({{
    general = {{
        gaps_in = {gap}, gaps_out = {{ top = {vertical}, bottom = {vertical}, left = {horizontal}, right = {horizontal} }}, border_size = {border},
    }},
    decoration = {{
        rounding = {radius}, rounding_power = 2,
        active_opacity = {opacity}, inactive_opacity = {opacity},
        blur = {{ enabled = true, size = 5, passes = 2, noise = 0.02, contrast = 1.0, brightness = 1.0, vibrancy = 0.2 }},
    }},
}})
'''
    return f'''# Generated by Quickshell; disable Hyprland appearance to restore your styling.
general {{
    gaps_in = {gap}
    gaps_out = {vertical}, {horizontal}, {vertical}, {horizontal}
    border_size = {border}
}}
decoration {{
    rounding = {radius}
    rounding_power = 2
    active_opacity = {opacity}
    inactive_opacity = {opacity}
    blur {{
        enabled = true
        size = 5
        passes = 2
        noise = 0.02
        contrast = 1.0
        brightness = 1.0
        vibrancy = 0.2
    }}
}}
'''


def hyprlock_path(value):
    if any(c in value for c in '\r\n\x00$#{}') or value != value.strip():
        raise ValueError('Hyprlock paths cannot contain newlines, $, #, braces, or leading/trailing whitespace. Rename the file or folder.')
    return value


