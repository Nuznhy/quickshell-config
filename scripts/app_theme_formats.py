def tmux(p):
    values = dict(p, **{'on_' + role: on_color(p[role]) for role in ('iris', 'rose', 'pine')})
    return '# Generated by Quickshell. Colors only; layout stays in tmux/theme.conf.\n' + ''.join(
        f'set-option -g @quickshell_{role} "{values[role]}"\n' for role in TMUX_ROLES)


def rofi(p):
    # Color overrides only: keep the user's font, dimensions and widget layout.
    values = dict(background=p['bg'], foreground=p['text'],
                  background_color=p['bg'], text_color=p['text'],
                  bordercolor=p['highlightMed'], separatorcolor=p['highlightMed'])
    # Also update the short color names used by the dotfiles' existing theme.
    values.update({key: p[role] for key, role in dict(bg='bg', cur='overlay', fgd='text',
                   cmt='muted', cya='foam', grn='pine', ora='rose', pur='iris', red='love', yel='gold').items()})
    states = {'normal': (p['bg'], p['text']), 'active': (p['surface'], p['foam']),
              'urgent': (p['love'], on_color(p['love']))}
    rules = []
    for variant in ('normal', 'alternate', 'selected'):
        for state, (bg, fg) in states.items():
            if variant == 'selected':
                bg = p['love'] if state == 'urgent' else p['iris']
                fg = on_color(bg)
            elif variant == 'alternate' and state == 'normal':
                bg = p['surface']
            values[f'{variant}-{state}-background'] = bg
            values[f'{variant}-{state}-foreground'] = fg
            rules.append(f'element {variant}.{state} {{ background-color: {bg}; text-color: {fg}; }}\n')
    for state, (bg, fg) in states.items():
        values[state + '-background'] = bg
        values[state + '-foreground'] = fg
    values['selected-background'] = p['iris']
    result = '/* Generated by Quickshell. Colors only. */\n* {\n' + ''.join(
        f'    {key.replace("_", "-")}: {value};\n' for key, value in values.items()) + '}\n'
    result += f'''window, mainbox, listview {{ background-color: {p['bg']}; }}
window, listview, message, sidebar {{ border-color: {p['highlightMed']}; }}
inputbar, message {{ background-color: {p['surface']}; text-color: {p['text']}; }}
textbox, button, case-indicator {{ background-color: transparent; text-color: {p['text']}; }}
entry {{ background-color: transparent; text-color: {p['text']}; placeholder-color: {p['muted']}; }}
prompt, textbox-prompt-colon {{ background-color: transparent; text-color: {p['iris']}; }}
num-filtered-rows, num-rows, textbox-num-sep {{ background-color: transparent; text-color: {p['subtle']}; }}
scrollbar {{ background-color: {p['surface']}; handle-color: {p['highlightHigh']}; }}
button selected {{ background-color: {p['iris']}; text-color: {on_color(p['iris'])}; }}
element-text, element-icon {{ background-color: inherit; text-color: inherit; }}
element-text {{ highlight: bold underline; }}
'''
    return result + ''.join(rules)


def ansi(p):
    normal = [p['bg'], p['love'], mix(p['foam'], p['gold'], .25), p['gold'],
              p['pine'], p['iris'], p['foam'], p['text']]
    return normal + [p['muted']] + [mix(c, p['text'], .25) for c in normal[1:7]] + [p['text']]


