ROLES = ('bg', 'surface', 'overlay', 'muted', 'subtle', 'text', 'love', 'gold',
         'rose', 'pine', 'foam', 'iris', 'highlightLow', 'highlightMed', 'highlightHigh')


def validate(palette, mode):
    if mode not in ('dark', 'light') or not isinstance(palette, dict):
        raise ValueError('Invalid theme mode or palette')
    if any(not isinstance(palette.get(k), str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', palette[k]) for k in ROLES):
        raise ValueError('The palette must contain all shell colors as #RRGGBB')
    return {k: palette[k].lower() for k in ROLES}


def rgb(color):
    return tuple(int(color[i:i + 2], 16) for i in (1, 3, 5))


def mix(a, b, amount):
    return '#' + ''.join(f'{round(x * (1 - amount) + y * amount):02x}' for x, y in zip(rgb(a), rgb(b)))


def on_color(background):
    # Black or white, whichever has better WCAG contrast with the accent.
    channels = [v / 255 for v in rgb(background)]
    linear = [v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4 for v in channels]
    luminance = sum(a * b for a, b in zip(linear, (.2126, .7152, .0722)))
    return '#000000' if luminance > .179 else '#ffffff'


