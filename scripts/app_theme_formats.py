def terminal(p, target):
    colors = ansi(p)
    if target == 'ghostty':
        return ''.join(f'palette = {i}={c}\n' for i, c in enumerate(colors)) + ''.join(
            f'{k} = {v}\n' for k, v in {'background': p['bg'], 'foreground': p['text'],
            'cursor-color': p['iris'], 'cursor-text': on_color(p['iris']),
            'selection-background': p['highlightHigh'], 'selection-foreground': p['text']}.items())
    colors_body = ''.join(f'{k}={v[1:]}\n' for k, v in {
        'background': p['bg'], 'foreground': p['text'], 'selection-background': p['highlightHigh'],
        'selection-foreground': p['text']}.items()) + ''.join(
        f'{"regular" if i < 8 else "bright"}{i % 8}={c[1:]}\n' for i, c in enumerate(colors))
    return '[colors-dark]\n' + colors_body + '\n[colors-light]\n' + colors_body


def kde(p):
    result = {'General': {'ColorScheme': NAME, 'Name': 'Quickshell'}, 'KDE': {'contrast': '4'}}
    for group, bg in [('Window', 'bg'), ('View', 'surface'), ('Button', 'overlay'), ('Selection', 'iris'),
                      ('Tooltip', 'overlay'), ('Complementary', 'surface'), ('Header', 'surface')]:
        selected = group == 'Selection'
        values = {'BackgroundNormal': p[bg], 'BackgroundAlternate': p['overlay'],
                  'ForegroundNormal': on_color(p['iris']) if selected else p['text'],
                  'ForegroundInactive': p['subtle'], 'ForegroundActive': p['iris'],
                  'ForegroundLink': p['pine'], 'ForegroundVisited': p['rose'],
                  'ForegroundNegative': p['love'], 'ForegroundNeutral': p['gold'],
                  'ForegroundPositive': p['foam'], 'DecorationFocus': p['iris'], 'DecorationHover': p['foam']}
        result['Colors:' + group] = {k: ','.join(map(str, rgb(v))) for k, v in values.items()}
    return result


def ini(sections):
    return ''.join(f'[{section}]\n' + ''.join(f'{k}={v}\n' for k, v in values.items()) + '\n'
                   for section, values in sections.items())


