def yazi(p):
    def style(fg, bg=None):
        return '{ fg = "' + fg + '"' + (', bg = "' + bg + '"' if bg else '') + ' }'
    sections = {'mgr': {'cwd': style(p['foam']), 'border_style': style(p['highlightHigh']),
                       'find_keyword': style(p['love']), 'marker_selected': style(p['iris'])},
                'tabs': {'active': style(on_color(p['iris']), p['iris']), 'inactive': style(p['subtle'], p['surface'])},
                'status': {'overall': style(p['text'], p['surface']), 'progress_normal': style(p['foam'], p['overlay']),
                           'progress_error': style(p['love'], p['overlay'])},
                'mode': {}, 'input': {'border': style(p['iris']), 'value': style(p['text'])},
                'pick': {'border': style(p['iris']), 'active': style(p['iris'])},
                'which': {'mask': style(p['text'], p['bg']), 'cand': style(p['foam']), 'desc': style(p['text'])},
                'confirm': {'border': style(p['iris']), 'title': style(p['text'])}}
    for mode, role in [('normal', 'iris'), ('select', 'foam'), ('unset', 'rose')]:
        sections['mode'][mode + '_main'] = style(on_color(p[role]), p[role])
        sections['mode'][mode + '_alt'] = style(p['text'], p['overlay'])
    flavor = ini(sections)
    syntax = {'name': 'Quickshell', 'settings': [{'settings': {'background': p['bg'], 'foreground': p['text']}}]}
    for scope, role in [('comment', 'muted'), ('string', 'foam'), ('keyword', 'iris'), ('constant', 'gold'),
                        ('entity.name.function', 'pine'), ('entity.name.type', 'rose'), ('invalid', 'love')]:
        syntax['settings'].append({'scope': scope, 'settings': {'foreground': p[role]}})
    return flavor, plistlib.dumps(syntax).decode()


